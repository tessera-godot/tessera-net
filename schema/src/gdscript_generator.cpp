#include "tessera/schema/gdscript_generator.hpp"

#include "tessera/schema/generator_text.hpp"

#include <string>
#include <vector>

namespace tessera::schema {

namespace {

// `player_one` gives `PLAYER_ONE`. A name in a file has only lowercase letters, digits and underscores, so
// different names give different results.
std::string UpperCase(const std::string& name) {
    std::string result = name;
    for (char& c : result) {
        if (c >= 'a' && c <= 'z') {
            c = static_cast<char>(c - 'a' + 'A');
        }
    }
    return result;
}

std::string TypeConstant(const TypeDecl& type) {
    return "TYPE_" + UpperCase(type.name);
}

// The dictionary that TesseraSchema.add_type takes for one property. The keys come in a fixed order: the name
// and the kind, then the numbers of the kind. The names of types and properties are lowercase letters, digits
// and underscores, so they go between quotes as they are. The note is not a key (add_type refuses a key it
// does not know), so it is written as a comment by the caller.
std::string Dictionary(const PropertyDecl& p) {
    std::string text = "{\"name\": \"" + p.name + "\", \"kind\": \"" + std::string(KindName(p.kind)) + "\"";
    switch (p.kind) {
    case Kind::Position:
        text += ", \"step\": " + FloatText(static_cast<float>(p.step)) +
                ", \"range\": " + FloatText(static_cast<float>(p.range));
        break;
    case Kind::Angle:
    case Kind::Mask:
        text += ", \"bits\": " + std::to_string(p.bits);
        break;
    case Kind::Integer:
        // `signed` is always written: it is the explicit form, and it is what the file means when it says
        // nothing.
        text += ", \"min\": " + Int64Literal(p.min_value) + ", \"max\": " + Int64Literal(p.max_value) +
                ", \"signed\": " + (p.is_signed ? "true" : "false");
        break;
    case Kind::Choice:
        text += ", \"count\": " + std::to_string(p.count);
        break;
    case Kind::Flag:
        break;
    }
    return text + "}";
}

} // namespace

std::string GenerateGdScript(const SchemaFile& file, uint64_t hash, const GdScriptOptions& options) {
    const std::vector<const TypeDecl*> types = TypesInOrder(file);
    Writer w;
    w.Line("# Generated by tessera_schema from " + NoticeName(options.source_name) +
           ". Do not edit: change that file and generate again.");
    w.Line("class_name " + options.class_name);
    w.Line("extends RefCounted");
    w.Line();
    w.Line("## The fingerprint of the whole schema file: the number TesseraSchema.get_hash() gives for the "
           "schema "
           "that");
    w.Line("## create() makes. It is a signed 64-bit integer, so it can be negative.");
    w.Line("const HASH: int = " + Int64Literal(static_cast<int64_t>(hash)));
    if (!types.empty()) {
        w.Line();
    }
    for (const TypeDecl* type : types) {
        if (!type->note.empty()) {
            w.Line("# " + type->note);
        }
        w.Line("const " + TypeConstant(*type) + " := " + std::to_string(type->type));
    }
    w.Line();
    w.Line();
    w.Line("## Describes every type of the file in a new TesseraSchema. A type that TesseraSchema refuses is "
           "reported");
    w.Line("## with push_error, and the schema is returned anyway, so that the mistake shows where it was "
           "made.");
    w.Line("static func create() -> TesseraSchema:");
    w.Line("\tvar schema := TesseraSchema.new()");
    for (const TypeDecl* type : types) {
        w.Line("\t_add_type(schema, " + TypeConstant(*type) + ", \"" + type->name + "\", [");
        for (const PropertyDecl& p : type->properties) {
            w.Line("\t\t" + Dictionary(p) + "," + (p.note.empty() ? "" : "  # " + p.note));
        }
        w.Line("\t])");
    }
    w.Line("\treturn schema");
    w.Line();
    w.Line();
    w.Line(
        "static func _add_type(schema: TesseraSchema, type_id: int, type_name: String, properties: Array) -> "
        "void:");
    w.Line("\tif schema.add_type(type_id, properties) != OK:");
    w.Line("\t\tpush_error(\"" + options.class_name +
           ": type '%s' (%d) was refused: %s\" % [type_name, type_id, schema.get_error()])");
    return w.Take();
}

} // namespace tessera::schema
