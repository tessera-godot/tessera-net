TESSERA_TEST(cpp_float_literals_round_trip) {
    // The text of a float, without its suffix, read again gives the same float.
    const auto round_trips = [](float value) {
        const std::string text = FormatFloat(value);
        if (text.empty() || text.back() != 'f') {
            return false;
        }
        const float back = std::strtof(text.substr(0, text.size() - 1).c_str(), nullptr);
        return std::memcmp(&back, &value, sizeof back) == 0;
    };
    TESSERA_CHECK(FormatFloat(0.01f) == "0.01f");
    TESSERA_CHECK(FormatFloat(2048.0f) == "2048.0f");
    TESSERA_CHECK(FormatFloat(1e30f) == "1e+30f");
    TESSERA_CHECK(FormatFloat(1e-30f) == "1e-30f");
    TESSERA_CHECK(FormatFloat(16777216.0f) == "16777216.0f");
    TESSERA_CHECK(FormatFloat(0.5f) == "0.5f");
    TESSERA_CHECK(FormatFloat(3.0f) == "3.0f");
    TESSERA_CHECK(FormatFloat(0.1f) == "0.1f");
    for (const float value : {0.01f, 2048.0f, 1e30f, 1e-30f, 16777216.0f, 0.1f, 1.0f / 3.0f, FLT_MAX, FLT_MIN,
                              1e-45f, -0.25f, 123456.789f}) {
        TESSERA_CHECK(round_trips(value));
    }
    std::mt19937 random(20240611u); // a fixed seed: the same numbers on every machine
    int checked = 0;
    for (int i = 0; i < 2000; ++i) {
        const uint32_t bits = random();
        float value;
        std::memcpy(&value, &bits, sizeof value);
        if (!(value == value) || value > FLT_MAX || value < -FLT_MAX) { // not a number, or an infinity
            continue;
        }
        ++checked;
        TESSERA_CHECK(round_trips(value));
    }
    TESSERA_CHECK(checked > 1900);
    // The text has a point or an exponent, so that it is a float and not an int.
    for (const float value : {1.0f, 100.0f, 1e10f, 0.0f}) {
        const std::string text = FormatFloat(value);
        TESSERA_CHECK(text.find_first_of(".e") != std::string::npos);
    }
}

TESSERA_TEST(cpp_float_literals_do_not_depend_on_the_locale) {
    // A locale whose decimal separator is a comma, if the system has one; the text must still have a point.
    const std::string before = std::setlocale(LC_ALL, nullptr);
    bool tried_one = false;
    for (const char* name : {"de_DE.UTF-8", "de_DE.utf8", "de_DE", "German_Germany.1252", "de-DE", "fr_FR.UTF-8", "pt_BR.UTF-8"}) {
        if (std::setlocale(LC_ALL, name) == nullptr) {
            continue;
        }
        if (std::string(std::localeconv()->decimal_point) != ".") {
            tried_one = true;
            TESSERA_CHECK(FormatFloat(0.01f) == "0.01f");
            TESSERA_CHECK(FormatFloat(2048.5f) == "2048.5f");
            TESSERA_CHECK(FormatFloat(1e-30f) == "1e-30f");
            const Generated g = GenerateFixture("all_kinds.json");
            TESSERA_CHECK(Has(g.text, "kAllKindsPositionStep = 0.01f;"));
            break;
        }
    }
    std::setlocale(LC_ALL, before.c_str());
    if (!tried_one) {
        std::printf("    (no locale with a decimal comma on this system: the test only checked the default one)\n");
        TESSERA_CHECK(FormatFloat(0.01f) == "0.01f");
    }
}

