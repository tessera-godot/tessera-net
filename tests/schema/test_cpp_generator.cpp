TESSERA_TEST(cpp_integer_column_types_are_the_smallest_that_fit) {
    struct Case {
        int64_t min;
        int64_t max;
        bool is_signed;
        const char* type;
    };
    const Case cases[] = {
        {0, 255, false, "uint8_t"},           {0, 256, false, "uint16_t"},
        {0, 65535, false, "uint16_t"},        {0, 65536, false, "uint32_t"},
        {0, 4294967295ll, false, "uint32_t"}, {0, 4294967296ll, false, "uint64_t"},
        {1000, 2000, false, "uint16_t"},      {-128, 127, true, "int8_t"},
        {-129, 127, true, "int16_t"},         {-32768, 32767, true, "int16_t"},
        {-32769, 0, true, "int32_t"},         {-2147483648ll, 2147483647ll, true, "int32_t"},
        {-2147483649ll, 0, true, "int64_t"},  {0, std::numeric_limits<int64_t>::max(), true, "int64_t"},
    };
    for (const Case& c : cases) {
        const ColumnSpec column = ColumnFor(Integer(c.min, c.max, c.is_signed));
        const bool ok = column.cpp_type == c.type;
        TESSERA_CHECK(ok);
        if (!ok) {
            std::printf("    %lld..%lld signed %d: wanted %s, got %s\n", static_cast<long long>(c.min),
                        static_cast<long long>(c.max), c.is_signed ? 1 : 0, c.type, column.cpp_type.c_str());
        }
    }
    // The size that goes to the replication code is the size of the type.
    TESSERA_CHECK(ColumnFor(Integer(0, 65535, false)).bytes == 2);
    TESSERA_CHECK(ColumnFor(Integer(0, 4294967296ll, false)).bytes == 8);
    // And the generated columns are these.
    const Generated g = GenerateFixture("all_kinds.json");
    TESSERA_CHECK(Has(g.text, "    uint8_t u8[::tessera::net::kPageSlots];"));
    TESSERA_CHECK(Has(g.text, "    uint16_t u16[::tessera::net::kPageSlots];"));
    TESSERA_CHECK(Has(g.text, "    uint32_t u32[::tessera::net::kPageSlots];"));
    TESSERA_CHECK(Has(g.text, "    uint64_t u64[::tessera::net::kPageSlots];"));
    TESSERA_CHECK(Has(g.text, "    int8_t s8[::tessera::net::kPageSlots];"));
    TESSERA_CHECK(Has(g.text, "    int16_t s16[::tessera::net::kPageSlots];"));
    TESSERA_CHECK(Has(g.text, "    int32_t s32[::tessera::net::kPageSlots];"));
    TESSERA_CHECK(Has(g.text, "    int64_t s64[::tessera::net::kPageSlots];"));
}

TESSERA_TEST(cpp_mask_and_choice_column_types) {
    const struct {
        uint32_t bits;
        const char* type;
    } masks[] = {{1, "uint8_t"},   {8, "uint8_t"},   {9, "uint16_t"},  {16, "uint16_t"},
                 {17, "uint32_t"}, {32, "uint32_t"}, {33, "uint64_t"}, {64, "uint64_t"}};
    for (const auto& m : masks) {
        TESSERA_CHECK(ColumnFor(WithBits(Kind::Mask, m.bits)).cpp_type == m.type);
    }
    const struct {
        uint32_t count;
        const char* type;
    } choices[] = {
        {2, "uint8_t"}, {256, "uint8_t"}, {257, "uint16_t"}, {65536, "uint16_t"}, {65537, "uint32_t"}};
    for (const auto& c : choices) {
        TESSERA_CHECK(ColumnFor(WithCount(c.count)).cpp_type == c.type);
    }
    TESSERA_CHECK(ColumnFor(PropertyDecl{"f", Kind::Flag, 0, 0, 0, 0, false, 0, 0, {}, {}, {}}).cpp_type ==
                  "uint8_t");
    TESSERA_CHECK(ColumnFor(WithBits(Kind::Angle, 12)).cpp_type == "float");
    const Generated g = GenerateFixture("all_kinds.json");
    TESSERA_CHECK(Has(g.text, "    uint8_t alive[::tessera::net::kPageSlots];"));
    TESSERA_CHECK(Has(g.text, "    uint8_t mask8[::tessera::net::kPageSlots];"));
    TESSERA_CHECK(Has(g.text, "    uint64_t mask40[::tessera::net::kPageSlots];"));
    TESSERA_CHECK(Has(g.text, "    uint8_t team[::tessera::net::kPageSlots];"));
    TESSERA_CHECK(Has(g.text, "    uint16_t species[::tessera::net::kPageSlots];"));
    TESSERA_CHECK(Has(g.text, "    float yaw[::tessera::net::kPageSlots];"));
}

