struct Generated {
    SchemaFile file;
    uint64_t hash = 0;
    std::string text;
};

// Reads, checks and generates a fixture, as the tool does.
Generated GenerateFixture(const std::string& name, const std::string& ns = "all_kinds") {
    Generated result;
    const ReadResult read = ReadSchema(ReadTestFile("fixtures/" + name));
    TESSERA_CHECK(read.file.has_value());
    if (!read.file) {
        return result;
    }
    result.file = *read.file;
    const CheckResult check = Check(result.file);
    TESSERA_CHECK(check.schema != nullptr);
    result.hash = check.hash;
    CppOptions options;
    options.ns = ns;
    options.source_name = name;
    result.text = GenerateCpp(result.file, result.hash, options);
    return result;
}

PropertyDecl Integer(int64_t min, int64_t max, bool is_signed) {
    PropertyDecl p;
    p.kind = Kind::Integer;
    p.min_value = min;
    p.max_value = max;
    p.is_signed = is_signed;
    return p;
}

PropertyDecl WithBits(Kind kind, uint32_t bits) {
    PropertyDecl p;
    p.kind = kind;
    p.bits = bits;
    return p;
}

PropertyDecl WithCount(uint32_t count) {
    PropertyDecl p;
    p.kind = Kind::Choice;
    p.count = count;
    return p;
}

std::string FirstLine(const std::string& text) {
    return text.substr(0, text.find('\n'));
}

std::string SecondLine(const std::string& text) {
    const size_t first = text.find('\n');
    return text.substr(first + 1, text.find('\n', first + 1) - first - 1);
}

// Where two texts first differ, as a line and a column, for a failure message.
std::string FirstDifference(const std::string& expected, const std::string& actual) {
    size_t line = 1;
    size_t column = 1;
    for (size_t i = 0; i < expected.size() && i < actual.size(); ++i) {
        if (expected[i] != actual[i]) {
            break;
        }
        if (expected[i] == '\n') {
            ++line;
            column = 1;
        } else {
            ++column;
        }
    }
    return "first difference at line " + std::to_string(line) + ", column " + std::to_string(column);
}

