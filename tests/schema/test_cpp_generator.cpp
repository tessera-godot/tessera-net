TESSERA_TEST(cpp_source_name_in_the_notice_is_plain_ASCII_on_one_line) {
    const Generated g = GenerateFixture("all_kinds.json");
    const auto first_line = [&](const std::string& name) {
        CppOptions options;
        options.ns = "x";
        options.source_name = name;
        const std::string text = GenerateCpp(g.file, g.hash, options);
        return text.substr(0, text.find('\n'));
    };
    const std::string neutral = "// Generated by tessera_schema from the schema file. Do not edit: change that file and generate again.";
    // A name with a line break, a control character, a byte outside ASCII or a backslash does not get into the comment.
    TESSERA_CHECK(first_line("evil\ninjection.json") == neutral);
    TESSERA_CHECK(first_line("tab\there.json") == neutral);
    TESSERA_CHECK(first_line("caf\xC3\xA9.json") == neutral);
    TESSERA_CHECK(first_line("ends_with_a_backslash\\") == neutral);
    TESSERA_CHECK(first_line("") == neutral);
    // A good name is kept.
    TESSERA_CHECK(first_line("my game (v2).json") ==
                  "// Generated by tessera_schema from my game (v2).json. Do not edit: change that file and generate again.");
}

