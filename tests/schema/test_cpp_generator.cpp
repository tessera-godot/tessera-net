TESSERA_TEST(cpp_namespace_option_nested_and_validated) {
    std::string why;
    for (const char* good :
         {"a", "a::b", "game_schema", "_x", "A1::b2", "tessera::server::example::schema", "game::tessera", "x_y",
          "_x1::y_"}) {
        TESSERA_CHECK(IsValidNamespace(good));
    }
    for (const char* bad :
         {"", "::a", "a::", "a::::b", "class", "a::class", "1a", "a b", "a-b", "a:b", ":", "a::1b", "__x", "x__y", "_X",
          "a::__b", "a::_C", "std", "a::std", "linux", "unix", "a::linux", "min", "errno", "stdin", "far"}) {
        why.clear();
        TESSERA_CHECK(!IsValidNamespace(bad, &why));
        TESSERA_CHECK(!why.empty());
    }
    why.clear();
    IsValidNamespace("class", &why);
    TESSERA_CHECK(Has(why, "keyword"));
    const Generated g = GenerateFixture("all_kinds.json", "a::b");
    TESSERA_CHECK(Has(g.text, "\nnamespace a::b {\n"));
    TESSERA_CHECK(Has(g.text, "\n} // namespace a::b\n"));
}

TESSERA_TEST(cpp_output_matches_the_golden_file) {
    const Generated g = GenerateFixture("all_kinds.json");
    const std::string golden = ReadTestFile("golden/all_kinds.hpp.expected");
    TESSERA_CHECK(!golden.empty());
    const bool same = g.text == golden;
    TESSERA_CHECK(same);
    if (!same) {
        std::printf("    %s (golden %zu bytes, generated %zu bytes)\n",
                    FirstDifference(golden, g.text).c_str(), golden.size(), g.text.size());
    }
}
